"""Strict text intake and ORIGINAL/EXPORTED accounting for the private hydride draft."""
import hashlib
import json
import math
from pathlib import Path, PurePosixPath
import re
from log_privacy import sanitize_log

SCHEMA = 'hydride-screening-capsule-v1'
ARCHIVE_ROOT = 'hydride-screening-delivery'
ROLES = frozenset({'F', 'G', 'F_h', 'F_cell'})
VOLUME = {'bytes': 3075, 'sha256': '01e4b1b4022b9d540a581f5e270262c1177a6b43f946f97a783cf71444830d4e'}
TEXT_SUFFIXES = frozenset({'.json', '.py', '.md', '.txt', '.log', '.stdout', '.stderr', '.exit', '.csv', '.tsv'})
PRIVATE_PATH = re.compile(r'/(?:home|root|tmp|run/user|mnt|workspace|opt|Users|private|var/folders)/[^\s\"\'<>`,;\)\]\}]+|[A-Za-z]:[\\/](?:Users|Documents and Settings)[\\/][^\s\"\'<>]+')
GPAW_USER_HEADER = re.compile(r'(?im)^[ \t]*User:[^\r\n]*(?:\r?\n|$)')
EMAIL = re.compile(r'[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}')
SENSITIVE_NAME = re.compile(r'(?i)(?:^|[-_. /])(?:credentials?|secrets?|tokens?|sessions?|provider|agent[-_]?reports?|full[-_]?reports?|encrypted[-_]reasoning)(?:$|[-_. /])')
SENSITIVE_FIELD = re.compile(r'(?i)^(?:password|api_key|access_token|refresh_token|bearer_token|private_key|credential|credentials|provider(?:_session|_response|_payload|_metadata)?|session(?:_id|_blob|_data)?|encrypted_reasoning|encrypted_content|reasoning_details|conversation_id|system_prompt|tool_calls|complete_agent_report|agent_report|agent_messages|agent_id)$')
LEAK_TEXT = re.compile(r'-----BEGIN (?:RSA |OPENSSH |EC )?PRIVATE KEY-----|\bBearer\s+[A-Za-z0-9._-]+|(?i:<(?:analysis|thinking)>|\"(?:session_id|provider_session|encrypted_reasoning|complete_agent_report|agent_messages)\"\s*:)')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def json_bytes(value):
    return (json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + '\n').encode('utf-8')


def json_value(path):
    def pairs(items):
        result = {}
        for key, value in items:
            require(key not in result, 'Duplicate JSON key: ' + key)
            result[key] = value
        return result
    def invalid(value):
        raise ValueError('Nonfinite JSON constant: ' + value)
    def floating(value):
        number = float(value)
        require(math.isfinite(number), 'Nonfinite JSON number')
        return number
    return json.loads(Path(path).read_bytes(), object_pairs_hook=pairs, parse_constant=invalid, parse_float=floating)


def safe_name(name):
    require(isinstance(name, str) and bool(name), 'Empty/nontext capsule path')
    path = PurePosixPath(name)
    require(not path.is_absolute() and str(path) == name and
            all(part not in ('', '.', '..') for part in name.split('/')) and
            not any(character in name for character in ('\\', ':', '\x00')),
            'Unsafe capsule member name')
    return path


def byte_binding(value):
    require(type(value) is dict and set(value) == {'bytes', 'sha256'} and
            type(value['bytes']) is int and value['bytes'] >= 0 and
            isinstance(value['sha256'], str) and re.fullmatch('[0-9a-f]{64}', value['sha256']),
            'Malformed byte binding')
    return value


def inspect_fields(value):
    if isinstance(value, dict):
        require(not any(SENSITIVE_FIELD.fullmatch(key) for key in value), 'Private structured field refused')
        for child in value.values():
            inspect_fields(child)
    elif isinstance(value, list):
        for child in value:
            inspect_fields(child)


def scan_text(name, data):
    safe_name(name)
    require(PurePosixPath(name).suffix.lower() in TEXT_SUFFIXES and not SENSITIVE_NAME.search(name),
            'Forbidden/nontext capsule payload: ' + name)
    text = data.decode('utf-8')
    require(not (PRIVATE_PATH.search(text) or GPAW_USER_HEADER.search(text) or
                 EMAIL.search(text) or LEAK_TEXT.search(text)), 'Export privacy scan failed: ' + name)
    if PurePosixPath(name).suffix.lower() == '.json':
        # JSON strictness is checked from disk on admission; field inspection covers generated bytes too.
        inspect_fields(json.loads(text))


def same_json(left, right):
    """Only floating quantities have tolerance; integers/bools/structure remain exact."""
    if type(left) is dict:
        return (type(right) is dict and left.keys() == right.keys() and
                all(same_json(value, right[key]) for key, value in left.items()))
    if type(left) is list:
        return (type(right) is list and len(left) == len(right) and
                all(same_json(a, b) for a, b in zip(left, right)))
    if type(left) is float and type(right) is float:
        return math.isfinite(left) and math.isfinite(right) and math.isclose(left, right, rel_tol=0, abs_tol=1e-9)
    return type(left) is type(right) and left == right


class Builder:
    """Transform only approved GPAW identity/location metadata in text logs."""
    def __init__(self, root):
        self.root = Path(root)
        self.files = {}

    def generated(self, name, data, original=None, changes=None):
        safe_name(name)
        require(name not in self.files and name != 'manifest.json', 'Duplicate/reserved capsule destination')
        scan_text(name, data)
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('xb') as output:
            output.write(data)
        self.files[name] = dict(ORIGINAL=original or digest(data), EXPORTED=digest(data),
                                transformation=changes or [])

    def add(self, source, name, header_only=False):
        source = Path(source)
        require(source.is_file() and not source.is_symlink(), 'Missing/unsafe source for ' + name)
        raw = source.read_bytes()
        text = raw.decode('utf-8')
        changes = []
        if header_only:
            require(source.suffix.lower() not in {'.json', '.py'}, 'Scientific bytes cannot be transformed')
            exported, changes = sanitize_log(raw)
            text = exported.decode('utf-8')
        self.generated(name, text.encode('utf-8'), digest(raw), changes)
